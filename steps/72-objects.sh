# shellcheck shell=bash
# The object store: Garage (S3-compatible) on one node, beside the database stack. Buckets and one
# access key per app come from config/objects/*.env; the server's own key (cx-backup) reads every
# bucket for the off-site copy. The S3 API listens on loopback and reaches the world through nginx
# on OBJECTS_FQDN (steps/60-nginx.sh); the admin API is loopback only. Nothing is served without a
# signature: no bucket has website access. Buckets are never deleted here.

OBJECTS_UID=10003

objects_describe() { echo "Garage object store: https://$OBJECTS_FQDN → 127.0.0.1:$OBJECTS_S3_PORT; buckets from config/objects/ ($(obj_names 2>/dev/null | tr '\n' ' '))"; }
objects_enabled() { is_true "$ENABLE_OBJECTS"; }

# ─── Generated files ───────────────────────────────────────────────────────────────
_obj_env() {
  cat <<EOF
# Generated by CX_PGSQL_Node_1 setup from config/server.env — do not edit.
OBJECTS_PROJECT=$(_obj_project)
OBJECTS_IMAGE=$OBJECTS_IMAGE
OBJECTS_CONTAINER=$OBJECTS_CONTAINER
OBJECTS_UID=$OBJECTS_UID
OBJECTS_DATA_DIR=$OBJECTS_DATA_DIR
OBJECTS_S3_PORT=$OBJECTS_S3_PORT
OBJECTS_ADMIN_PORT=$OBJECTS_ADMIN_PORT
OBJECTS_MEMORY_LIMIT=$OBJECTS_MEMORY_LIMIT
STACK_NETWORK=${COMPOSE_PROJECT_NAME}_db
EOF
}

# No secret in here: Garage reads each from its own file.
_obj_garage_toml() {
  cat <<EOF
# Generated by CX_PGSQL_Node_1 setup (steps/72-objects.sh) — do not edit.
metadata_dir = "/var/lib/garage/meta"
data_dir = "/var/lib/garage/data"
db_engine = "lmdb"
# One node, so no other copy exists until the hourly off-site one: reach the disk before answering.
metadata_fsync = true
data_fsync = true
# Snapshots of the metadata beside it, for a quick recovery from a damaged LMDB. A lost server
# comes back from the off-site copy instead (docs/Restore.md).
metadata_auto_snapshot_interval = "6h"
replication_factor = 1
consistency_mode = "consistent"
# Pictures and PDFs are mostly compressed already; zstd at its lightest catches the rest cheaply.
compression_level = 1

rpc_bind_addr = "[::]:3901"
rpc_public_addr = "127.0.0.1:3901"
rpc_secret_file = "/run/cx-secrets/objects-rpc-secret"

[s3_api]
s3_region = "garage"
api_bind_addr = "[::]:3900"
public_endpoint = "https://$OBJECTS_FQDN"

[admin]
api_bind_addr = "[::]:3903"
admin_token_file = "/run/cx-secrets/objects-admin-token"
metrics_token_file = "/run/cx-secrets/objects-metrics-token"
EOF
}

# "path|mode|generator"
_obj_files() {
  cat <<EOF
$OBJECTS_DIR/.env|0644|_obj_env
$OBJECTS_DIR/garage.toml|0644|_obj_garage_toml
EOF
}

_obj_secrets() { printf '%s\n' objects-rpc-secret objects-admin-token objects-metrics-token; }
_obj_secret_copy_ok() {
  local f="$OBJECTS_DIR/secrets/$1"
  [[ -f "$f" ]] && cmp -s "$(secret_path "$1")" "$f" && [[ "$(stat -c %u:%a "$f")" == "$OBJECTS_UID:400" ]]
}

# ─── Checks ────────────────────────────────────────────────────────────────────────
# Its own project, named on the command line: the setup exports COMPOSE_PROJECT_NAME for the database
# stack, and that would otherwise win over compose.yml's `name:` — putting Garage in the stack's
# project, where either one's `--remove-orphans` would remove the other.
_obj_project() { printf '%s-objects' "$STACK_NAME"; }
_obj_compose() { (cd "$OBJECTS_DIR" && docker compose -p "$(_obj_project)" "$@"); }

_obj_dirs_ok() {
  local d
  for d in "$OBJECTS_DATA_DIR" "$OBJECTS_DATA_DIR/meta" "$OBJECTS_DATA_DIR/data"; do
    [[ "$(stat -c %u:%a "$d" 2>/dev/null)" == "$OBJECTS_UID:700" ]] || return 1
  done
}

_obj_up_to_date() {
  local want have
  want=$(_obj_compose config --hash garage 2>/dev/null | awk '{print $2}') || return 1
  have=$(docker inspect -f '{{index .Config.Labels "com.docker.compose.config-hash"}}' "$OBJECTS_CONTAINER" 2>/dev/null) || return 1
  [[ -n "$want" && "$have" == "$want" ]] && _obj_in_own_project
}
_obj_in_own_project() {
  [[ "$(docker inspect -f '{{index .Config.Labels "com.docker.compose.project"}}' "$OBJECTS_CONTAINER" 2>/dev/null)" == "$(_obj_project)" ]]
}

_obj_no_duplicate_buckets() { [[ -z "$(obj_buckets | sort | uniq -d)" ]]; }

_obj_check_app() {
  check_begin
  local b
  for b in $OBJ_BUCKETS; do chk "bucket $b" obj_bucket_exists "$b"; done
  chk "access key for $OBJ_NAME" obj_key_exists "$OBJ_NAME"
  chk "$OBJ_NAME's key: read and write on its buckets, nothing else" _obj_grants_are "$OBJ_NAME" "$(obj_app_grants)"
  # Hand the results back to the parent shell (this runs in obj_each's subshell).
  printf '%s\t%s\t' "$CHECK_PASS" "$CHECK_FAIL"
  printf '%s\x1f' "${CHECK_LINES[@]}"
  printf '\n'
}
_obj_grants_are() { [[ "$(obj_key_grants "$1" 2>/dev/null)" == "$2" ]]; }

# Each app's items, merged into this shell's counts. A function of its own because of the IFS
# change, which must not reach the rest of objects_check.
_obj_check_apps() {
  local pass fail lines l IFS
  while IFS=$'\t' read -r pass fail lines; do
    CHECK_PASS=$((CHECK_PASS + pass))
    CHECK_FAIL=$((CHECK_FAIL + fail))
    IFS=$'\x1f'
    for l in $lines; do [[ -n "$l" ]] && CHECK_LINES+=("$l"); done
    unset IFS
  done < <(obj_each _obj_check_app)
}

# A request signed with cx-backup's key on the local S3 API.
_obj_signed_ok() { (obj_rclone_env "$OBJ_BACKUP_KEY" && rclone --config /dev/null lsf "cxobj:$OBJ_VERIFY_BUCKET" >/dev/null); }
# The same without a signature: Garage must refuse it.
_obj_unsigned_refused() {
  [[ "$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 "http://127.0.0.1:$OBJECTS_S3_PORT/$OBJ_VERIFY_BUCKET/")" == 403 ]]
}

# The whole public path, as an app would use it: TLS at nginx on OBJECTS_FQDN, the Host header
# passed through, a SigV4 signature checked by Garage. Resolved to this machine, so it works
# before DNS does (and skips verification while the certificate is the self-signed one).
_obj_public_path_ok() {
  local insecure=()
  tls_is_self_signed "$OBJECTS_FQDN" && insecure=(-k)
  printf 'user = "%s:%s"\n' "$(obj_key_id "$OBJ_BACKUP_KEY")" "$(cat "$(secret_path "$(obj_key_secret_secret "$OBJ_BACKUP_KEY")")")" |
    curl -fsS -o /dev/null --max-time 10 "${insecure[@]}" -K - --aws-sigv4 "aws:amz:garage:s3" \
      --resolve "$OBJECTS_FQDN:443:127.0.0.1" "https://$OBJECTS_FQDN/$OBJ_VERIFY_BUCKET/?list-type=2"
}

_obj_offsite_ok() { is_true "$BACKUP_UPLOAD" && remote_configured; }

objects_check() {
  chk "data directories in $OBJECTS_DATA_DIR (uid $OBJECTS_UID, 0700)" _obj_dirs_ok
  chk "compose project in $OBJECTS_DIR" cmp -s "$PROJECT_DIR/stack/objects/compose.yml" "$OBJECTS_DIR/compose.yml"
  local path mode gen name
  while IFS='|' read -r path mode gen; do
    chk_render "${path#"$OBJECTS_DIR"/}" "$path" "$gen"
  done < <(_obj_files)
  while read -r name; do chk "secret $name for Garage" _obj_secret_copy_ok "$name"; done < <(_obj_secrets)
  chk "Garage running and healthy" _stack_container_healthy "$OBJECTS_CONTAINER"
  chk "container matches its configuration ($OBJECTS_IMAGE, project $(_obj_project))" _obj_up_to_date
  if ! obj_api GET GetClusterStatus >/dev/null 2>&1; then
    chk "Garage's admin API answers" false
    return 0
  fi
  chk "layout: this node, $OBJECTS_CAPACITY" obj_layout_ok
  chk "Garage reports healthy" obj_health_ok
  chk "no bucket claimed by two apps" _obj_no_duplicate_buckets
  _obj_check_apps
  [[ -n "$(obj_names)" ]] || chk_note "no apps configured (add config/objects/<app>.env)"
  chk "bucket $OBJ_VERIFY_BUCKET (restore test scratch)" obj_bucket_exists "$OBJ_VERIFY_BUCKET"
  chk "backup key: read on every bucket, write only on $OBJ_VERIFY_BUCKET" _obj_grants_are "$OBJ_BACKUP_KEY" "$(obj_backup_grants)"
  chk "signed request on the S3 API" _obj_signed_ok
  chk "unsigned request refused" _obj_unsigned_refused
  chk "signed request through https://$OBJECTS_FQDN (nginx)" _obj_public_path_ok
  chk_soft "objects copied off-site (BACKUP_UPLOAD and a configured remote)" _obj_offsite_ok
  return 0
}

# ─── Apply ─────────────────────────────────────────────────────────────────────────
_obj_wait_admin() {
  local _
  for _ in $(seq 1 30); do
    obj_api GET GetClusterStatus >/dev/null 2>&1 && return 0
    sleep 1
  done
  return 1
}

_obj_apply_app() {
  info "Objects for $OBJ_NAME: $OBJ_BUCKETS"
  local b
  for b in $OBJ_BUCKETS; do obj_bucket_create "$b"; done
  obj_key_ensure "$OBJ_NAME"
  obj_key_converge "$OBJ_NAME" "$(obj_app_grants)"
}

objects_apply() {
  ensure_pkgs curl jq rclone
  command -v docker >/dev/null || die "Apply the docker step first."
  docker network inspect "${COMPOSE_PROJECT_NAME}_db" >/dev/null 2>&1 || die "The stack's network is missing — apply the stack step first."
  _obj_no_duplicate_buckets || die "A bucket is listed by two apps in config/objects/: $(obj_buckets | sort | uniq -d | tr '\n' ' ')"

  install -d -m 0700 -o "$OBJECTS_UID" -g "$OBJECTS_UID" "$OBJECTS_DATA_DIR" "$OBJECTS_DATA_DIR/meta" "$OBJECTS_DATA_DIR/data"
  install -d -m 0750 -o root -g root "$OBJECTS_DIR"
  install -m 0644 "$PROJECT_DIR/stack/objects/compose.yml" "$OBJECTS_DIR/compose.yml"
  local path mode gen
  while IFS='|' read -r path mode gen; do
    "$gen" | write_if_changed "$path" "$mode" && info "Wrote ${path#"$OBJECTS_DIR"/}"
  done < <(_obj_files)

  # Secrets (generated once) and the copies Garage reads. The RPC secret must be 32 bytes of hex.
  secret_hex objects-rpc-secret 32 >/dev/null
  secret objects-admin-token 48 >/dev/null
  secret objects-metrics-token 48 >/dev/null
  secret objects-crypt-pass 48 >/dev/null
  secret objects-crypt-salt 48 >/dev/null
  install -d -m 0500 -o "$OBJECTS_UID" -g "$OBJECTS_UID" "$OBJECTS_DIR/secrets"
  local name
  while read -r name; do
    install -m 0400 -o "$OBJECTS_UID" -g "$OBJECTS_UID" "$(secret_path "$name")" "$OBJECTS_DIR/secrets/$name"
  done < <(_obj_secrets)

  # A container of that name in another compose project (an older setup) is replaced; the data is on the host.
  if docker inspect "$OBJECTS_CONTAINER" >/dev/null 2>&1 && ! _obj_in_own_project; then
    warn "$OBJECTS_CONTAINER belongs to another compose project — recreating it in $(_obj_project)"
    docker rm -f "$OBJECTS_CONTAINER" >/dev/null
  fi
  info "Starting Garage ($OBJECTS_IMAGE)"
  _obj_compose up -d --wait --wait-timeout 120 || {
    _obj_compose logs --tail 50
    die "Garage didn't become healthy (logs above)."
  }
  _obj_wait_admin || die "Garage's admin API on 127.0.0.1:$OBJECTS_ADMIN_PORT doesn't answer."

  obj_layout_ok || obj_layout_apply
  local _
  for _ in $(seq 1 30); do obj_health_ok && break; sleep 1; done

  obj_each _obj_apply_app
  obj_bucket_create "$OBJ_VERIFY_BUCKET"
  obj_key_ensure "$OBJ_BACKUP_KEY"
  obj_key_converge "$OBJ_BACKUP_KEY" "$(obj_backup_grants)"

  _obj_offsite_ok || warn "Objects have no off-site copy until BACKUP_UPLOAD is on and a remote is configured (bin/remote.sh dropbox-auth)."
}

objects_teardown() {
  [[ -f "$OBJECTS_DIR/compose.yml" ]] && { _obj_compose down --remove-orphans || true; }
  if ((PURGE)); then
    warn "Deleting every object ($OBJECTS_DATA_DIR) and Garage's configuration ($OBJECTS_DIR). The off-site copy is kept."
    rm -rf "${OBJECTS_DATA_DIR:?}" "${OBJECTS_DIR:?}"
  else
    info "Garage stopped and removed. Objects in $OBJECTS_DATA_DIR are kept (--purge deletes them)."
  fi
}
