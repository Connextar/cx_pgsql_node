_stack_pg_hba() {
  cat <<EOF
# Generated by CX_PGSQL_Node_1 setup (steps/70-stack.sh) — do not edit.
# TYPE    DATABASE     USER      ADDRESS            METHOD
# Inside the container: the postgres OS user, no password (setup, backups).
local     all          postgres                     peer
local     all          all                          scram-sha-256
host      all          all       127.0.0.1/32       scram-sha-256
host      all          all       ::1/128            scram-sha-256
# The stack's own network (PgBouncer, health, n8n; the host's loopback arrives from here too).
host      all          all       $DOCKER_SUBNET     scram-sha-256
# The superuser never logs in from outside.
host      all          postgres  0.0.0.0/0          reject
host      all          postgres  ::/0               reject
# Everyone else: TLS and a SCRAM password, or nothing.
hostssl   all          all       0.0.0.0/0          scram-sha-256
hostssl   all          all       ::/0               scram-sha-256
host      all          all       0.0.0.0/0          reject
host      all          all       ::/0               reject
EOF
}

_stack_pgbouncer_db_lines() {
  is_true "$DB_PGBOUNCER" || return 0
  printf '%s = host=postgres port=5432 dbname=%s pool_size=%s\n' "$DB_NAME" "$DB_NAME" "$DB_POOL_SIZE"
  # Session pooling under a second name: for migrations, advisory locks and LISTEN/NOTIFY.
  printf '%s_session = host=postgres port=5432 dbname=%s pool_mode=session pool_size=%s\n' "$DB_NAME" "$DB_NAME" "$DB_SESSION_POOL_SIZE"
}

