# Per-container copies of the secrets each one reads: "secret|dir|uid"
_stack_secret_copies() {
  printf 'postgres-password|postgres|%s\n' "$PG_UID"
  printf 'cx-monitor-password|health|%s\n' "$HEALTH_UID"
  printf 'health-token|health|%s\n' "$HEALTH_UID"
  if is_true "$ENABLE_N8N"; then
    printf 'n8n-db-password|n8n|%s\n' "$N8N_UID"
    printf 'n8n-encryption-key|n8n|%s\n' "$N8N_UID"
  fi
}
_stack_secret_copy_ok() {
  local name=$1 dir=$2 uid=$3 f="$STACK_DIR/secrets/$2/$1"
  [[ -f "$f" ]] && cmp -s "$(secret_path "$name")" "$f" && [[ "$(stat -c %u "$f")" == "$uid" ]]
}

# ─── Containers ────────────────────────────────────────────────────────────────────
_compose() { (cd "$STACK_DIR" && docker compose "$@"); }
_stack_services() {
  printf 'postgres\npgbouncer\nhealth\n'
  is_true "$ENABLE_N8N" && printf 'n8n\n'
  return 0
}
_stack_container_healthy() {
  local c=$1 state
  state=$(docker inspect -f '{{.State.Status}} {{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$c" 2>/dev/null) || return 1
  [[ "$state" == "running healthy" || "$state" == "running none" ]]
}
# Compose's own record of the configuration each container was created from.
_stack_up_to_date() {
  local svc want have
  [[ -f "$STACK_DIR/compose.yml" ]] || return 1
  while read -r svc want; do
    have=$(docker inspect -f '{{index .Config.Labels "com.docker.compose.config-hash"}}' "${STACK_NAME}-$svc" 2>/dev/null) || return 1
    [[ "$have" == "$want" ]] || return 1
  done < <(_compose config --hash '*' 2>/dev/null)
}
_stack_no_pending_restart() { [[ "$(pg_value 'SELECT count(*) FROM pg_settings WHERE pending_restart')" == 0 ]]; }
_stack_cluster_roles_ok() {
  [[ "$(pg_value "SELECT count(*) FROM pg_roles WHERE rolname IN ('cx_monitor','pgbouncer_auth') AND rolcanlogin")" == 2 ]] &&
    [[ "$(pg_value "SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = 'pgbouncer' AND p.proname = 'get_auth'")" == 1 ]] &&
    [[ "$(pg_value "SELECT count(*) FROM pg_extension WHERE extname = 'pg_stat_statements'")" == 1 ]]
}
_stack_stanza_ok() {
  local code
  code=$(docker exec -u postgres "$PG_CONTAINER" pgbackrest --stanza="$PGBACKREST_STANZA" --output=json info 2>/dev/null | jq -r '.[0].status.code') || return 1
  # 0 = ok, 2 = no backup yet (the first one runs on schedule)
  [[ "$code" == 0 || "$code" == 2 ]]
}

stack_check() {
  local line path mode owner gen svc
  chk "postgresql-client on the host" pkg_installed postgresql-client
  chk "data directory $PG_DATA_DIR (uid $PG_UID, 0700)" sh -c "[ \"\$(stat -c %u:%a '$PG_DATA_DIR')\" = '$PG_UID:700' ]"
  chk "compose project in $STACK_DIR" test -f "$STACK_DIR/compose.yml"
  chk "stack sources match this project" _stack_sources_in_sync
  while IFS='|' read -r path mode owner gen; do
    chk_render "${path#"$STACK_DIR"/}" "$path" "$gen"
  done < <(_stack_files)
  while IFS='|' read -r line path owner; do
    chk "secret $line for $path" _stack_secret_copy_ok "$line" "$path" "$owner"
  done < <(_stack_secret_copies)
  chk "certificate installed for Postgres/PgBouncer" tls_stack_in_sync
  for svc in $(_stack_services); do
    chk "$svc running and healthy" _stack_container_healthy "${STACK_NAME}-$svc"
  done
  chk "containers match their configuration" _stack_up_to_date
  chk_soft "every container starts again after a reboot" _stack_all_restart
  chk "no setting waiting for a restart" _stack_no_pending_restart
  chk "cluster roles (cx_monitor, pgbouncer_auth) and pg_stat_statements" _stack_cluster_roles_ok
  chk "monitor login through PgBouncer with TLS" pg_login_ok cx_monitor postgres cx-monitor-password 127.0.0.1 "$PGBOUNCER_PUBLIC_PORT" require
  is_true "$BACKUP_PITR" && chk "pgBackRest stanza '$PGBACKREST_STANZA'" _stack_stanza_ok
  return 0
}

# A running container marked as manually stopped stays down after a reboot (see containers_not_restarting).
# Only a restart clears the mark, so this warns rather than repairs: cx-pgsql restart <service>.
_stack_all_restart() {
  local svc names=() bad
  for svc in $(_stack_services); do names+=("${STACK_NAME}-$svc"); done
  bad=$(containers_not_restarting "${names[@]}")
  [[ -z "$bad" ]] && return 0
  warn "Would stay down after a reboot: $(echo $bad) — clear it with  cx-pgsql restart ${bad//${STACK_NAME}-/}"
  return 1
}

_stack_sources_in_sync() {
  # Contents only (checksums); a directory's timestamp isn't a difference.
  rsync -rnc --delete --itemize-changes --exclude node_modules --exclude test \
    "$PROJECT_DIR/stack/health/" "$STACK_DIR/health/" 2>/dev/null | grep -v '^\.d' | grep_q . && return 1
  cmp -s "$PROJECT_DIR/stack/compose.yml" "$STACK_DIR/compose.yml" &&
    cmp -s "$PROJECT_DIR/stack/postgres/Dockerfile" "$STACK_DIR/postgres/Dockerfile" &&
    cmp -s "$PROJECT_DIR/stack/pgbouncer/Dockerfile" "$STACK_DIR/pgbouncer/Dockerfile"
}

_stack_cluster_sql() {
  cat <<'EOF'
SELECT 'CREATE ROLE cx_monitor LOGIN' WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'cx_monitor') \gexec
GRANT pg_monitor TO cx_monitor;
SELECT 'CREATE ROLE pgbouncer_auth LOGIN' WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'pgbouncer_auth') \gexec
CREATE SCHEMA IF NOT EXISTS pgbouncer AUTHORIZATION postgres;
-- PgBouncer asks this for a client's SCRAM secret. Never for a superuser or for itself.
CREATE OR REPLACE FUNCTION pgbouncer.get_auth(p_usename text)
RETURNS TABLE (usename name, passwd text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog AS $$
  SELECT rolname, rolpassword FROM pg_authid
  WHERE rolname = p_usename AND rolcanlogin AND NOT rolsuper AND rolname <> 'pgbouncer_auth'
    AND (rolvaliduntil IS NULL OR rolvaliduntil > now());
$$;
REVOKE ALL ON SCHEMA pgbouncer FROM PUBLIC;
REVOKE ALL ON FUNCTION pgbouncer.get_auth(text) FROM PUBLIC;
GRANT USAGE ON SCHEMA pgbouncer TO pgbouncer_auth;
GRANT EXECUTE ON FUNCTION pgbouncer.get_auth(text) TO pgbouncer_auth;
CREATE EXTENSION IF NOT EXISTS pg_stat_statements;
-- Tenants connect only to their own databases.
REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;
GRANT CONNECT ON DATABASE postgres TO cx_monitor, pgbouncer_auth;
EOF
}

stack_apply() {
  ensure_pkgs rsync jq postgresql-client
  command -v docker >/dev/null || die "Apply the docker step first."

  # Directories, owned by whoever writes them inside the containers. The stack is root's: it
  # doesn't take the apps group's setgid bit and default ACLs that /data/apps hands down.
  install -d -m 0750 -o root -g root "$STACK_DIR"
  chmod g-s "$STACK_DIR"
  setfacl -R -b "$STACK_DIR"
  install -d -m 0755 "$STACK_DIR/config" "$STACK_DIR/config/postgres" "$STACK_DIR/config/postgres/conf.d" "$STACK_DIR/postgres" "$STACK_DIR/pgbouncer"
  install -d -m 0750 -o "$PG_UID" -g "$PG_GID" "$STACK_DIR/config/pgbouncer" "$STACK_DIR/config/pgbackrest"
  install -d -m 0750 -o "$PG_UID" -g "$PG_GID" "$STACK_LOGS_DIR" "$STACK_LOGS_DIR/postgres" "$STACK_LOGS_DIR/pgbouncer" "$STACK_LOGS_DIR/pgbackrest"
  install -d -m 0755 "$DATA_ROOT" "$DATA_ROOT/$PG_MAJOR" "$BACKUP_ROOT"
  install -d -m 0700 -o "$PG_UID" -g "$PG_GID" "$PG_DATA_DIR"
  install -d -m 0750 -o "$PG_UID" -g "$PG_GID" "$BACKUP_ROOT/pgbackrest"
  install -d -m 0700 "$BACKUP_ROOT/dumps"
  install -d -m 0755 "$BACKUP_ROOT/status"
  is_true "$ENABLE_N8N" && install -d -m 0700 -o "$N8N_UID" -g "$N8N_UID" "$DATA_ROOT/n8n"
  [[ -f "$STACK_DIR/config/postgres/conf.d/local.conf" ]] ||
    printf '# Your own postgresql.conf overrides (read last; never overwritten by the setup).\n' >"$STACK_DIR/config/postgres/conf.d/local.conf"

  # Sources.
  rsync -a --delete --exclude node_modules --exclude test "$PROJECT_DIR/stack/health/" "$STACK_DIR/health/"
  install -m 0644 "$PROJECT_DIR/stack/compose.yml" "$STACK_DIR/compose.yml"
  install -m 0644 "$PROJECT_DIR/stack/postgres/Dockerfile" "$STACK_DIR/postgres/Dockerfile"
  install -m 0644 "$PROJECT_DIR/stack/pgbouncer/Dockerfile" "$STACK_DIR/pgbouncer/Dockerfile"

  # Secrets (generated once) and the copies each container reads.
  local name dir uid
  for name in postgres-password cx-monitor-password pgbouncer-auth-password health-token pgbackrest-cipher-pass; do secret "$name" >/dev/null; done
  is_true "$ENABLE_N8N" && { secret n8n-db-password >/dev/null; secret n8n-encryption-key 48 >/dev/null; }
  while IFS='|' read -r name dir uid; do
    install -d -m 0500 -o "$uid" -g "$uid" "$STACK_DIR/secrets/$dir"
    install -m 0400 -o "$uid" -g "$uid" "$(secret_path "$name")" "$STACK_DIR/secrets/$dir/$name"
  done < <(_stack_secret_copies)
  chmod 0711 "$STACK_DIR/secrets"

  # Certificates (the self-signed placeholder until Let's Encrypt has issued one).
  tls_ensure_placeholder "$SERVER_FQDN"
  tls_sync_stack || true

  # Configuration.
  local path mode owner gen pg_conf_changed=0 bouncer_changed=0
  while IFS='|' read -r path mode owner gen; do
    if "$gen" | write_if_changed "$path" "$mode" "$owner"; then
      info "Wrote ${path#"$STACK_DIR"/}"
      case $path in */config/postgres/*) pg_conf_changed=1 ;; */config/pgbouncer/*) bouncer_changed=1 ;; esac
    fi
  done < <(_stack_files)

  # Containers: Postgres first, then its own roles (and n8n's database), then everything else.
  info "Building images and starting the stack (first run pulls the base images)"
  _compose build --quiet
  _stack_up postgres
  _stack_cluster_sql | pg_sql -d postgres
  pg_login_ok cx_monitor postgres cx-monitor-password 127.0.0.1 "$PG_DIRECT_PORT" || pg_set_password cx_monitor cx-monitor-password
  pg_login_ok pgbouncer_auth postgres pgbouncer-auth-password 127.0.0.1 "$PG_DIRECT_PORT" || pg_set_password pgbouncer_auth pgbouncer-auth-password
  if is_true "$ENABLE_N8N"; then
    # n8n needs its database before it starts (the databases step keeps it in shape afterwards).
    _stack_provision_n8n
  fi
  _stack_up

  # Settings: reload, then restart if one needs it and that's allowed.
  if ((pg_conf_changed)); then pg_value 'SELECT pg_reload_conf()' >/dev/null; sleep 1; fi
  if ! _stack_no_pending_restart; then
    if is_true "$PG_ALLOW_AUTO_RESTART"; then
      warn "Restarting Postgres for: $(pg_value "SELECT string_agg(name, ', ') FROM pg_settings WHERE pending_restart")"
      _compose restart postgres
      _compose up -d --wait --wait-timeout 300
    else
      warn "Postgres needs a restart for: $(pg_value "SELECT string_agg(name, ', ') FROM pg_settings WHERE pending_restart")"
      warn "Run: cx-pgsql restart postgres  (or set PG_ALLOW_AUTO_RESTART=true)"
    fi
  fi
  ((bouncer_changed)) && pgbouncer_reload >/dev/null

  # pgBackRest: the stanza must exist before WAL can be archived.
  if is_true "$BACKUP_PITR" && ! _stack_stanza_ok; then
    info "Creating the pgBackRest stanza '$PGBACKREST_STANZA'"
    docker exec -u postgres "$PG_CONTAINER" pgbackrest --stanza="$PGBACKREST_STANZA" stanza-create
    docker exec -u postgres "$PG_CONTAINER" pgbackrest --stanza="$PGBACKREST_STANZA" check
  fi
}

# docker compose up --wait for the named services (all when none), with logs on failure.
_stack_up() {
  _compose up -d --remove-orphans --wait --wait-timeout 300 "$@" || {
    _compose ps
    _compose logs --tail 50 "$@"
    die "The stack didn't become healthy (logs above)."
  }
}

_stack_provision_n8n() {
  (
    _db_defaults
    # shellcheck disable=SC2034 # read by _db_finalize and _dbs_apply_one
    DB_NAME=n8n DB_USER=n8n DB_SECRET=n8n-db-password DB_PGBOUNCER=false
    _db_finalize n8n
    _dbs_apply_one
  )
}

stack_teardown() {
  if [[ -f "$STACK_DIR/compose.yml" ]]; then
    _compose --profile n8n down --remove-orphans || true
  fi
  if ((PURGE)); then
    warn "Deleting the database files ($DATA_ROOT), the stack ($STACK_DIR) and the LOCAL backups ($BACKUP_ROOT)."
    rm -rf "${DATA_ROOT:?}" "${STACK_DIR:?}" "${BACKUP_ROOT:?}"
    docker image rm "cx-pgsql/postgres:$PG_VERSION" "cx-pgsql/pgbouncer:$PG_VERSION" cx-pgsql/health:local 2>/dev/null || true
  else
    info "Containers stopped and removed. Data in $PG_DATA_DIR and backups in $BACKUP_ROOT are kept (--purge deletes them)."
  fi
}
