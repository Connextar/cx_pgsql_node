# shellcheck shell=bash
# The Docker stack in $STACK_DIR: Postgres (+ pgBackRest), PgBouncer, the health service,
# optionally n8n. Generates every configuration file from config/, starts the containers,
# creates the cluster's own roles and the pgBackRest stanza.

# Container users with uids of their own: 1000 is usually the first person's account on the host.
HEALTH_UID=10001
N8N_UID=10002

stack_describe() { echo "Postgres $PG_VERSION + PgBouncer + health$(is_true "$ENABLE_N8N" && printf ' + n8n') in $STACK_DIR"; }

# ─── Sizing ────────────────────────────────────────────────────────────────────────
_mb_of() { # "6g" / "512m" / "2048" (MB) → MB
  local v=${1,,}
  case $v in
    *g | *gb) echo $((${v%%g*} * 1024)) ;;
    *m | *mb) echo "${v%%m*}" ;;
    *) echo "$v" ;;
  esac
}
# PG_MEMORY_LIMIT as Docker takes it: `auto` = 60 % of the machine's RAM.
_stack_pg_memory_limit() {
  if [[ "${PG_MEMORY_LIMIT,,}" == auto ]]; then
    printf '%sm' $(($(awk '/^MemTotal:/{print $2}' /proc/meminfo) * 6 / 10 / 1024))
  else
    printf '%s' "$PG_MEMORY_LIMIT"
  fi
}

_stack_tune() {
  local ram_mb limit_mb cpus sb ecs wm mwm
  ram_mb=$(($(awk '/^MemTotal:/{print $2}' /proc/meminfo) / 1024))
  limit_mb=$(_mb_of "$(_stack_pg_memory_limit)")
  ((limit_mb > 0 && limit_mb < ram_mb)) && ram_mb=$limit_mb
  cpus=$(nproc)
  sb=$((ram_mb / 4))
  ecs=$((ram_mb * 7 / 10))
  wm=$(((ram_mb - sb) / (PG_MAX_CONNECTIONS * 3)))
  ((wm < 4)) && wm=4
  mwm=$((ram_mb / 16))
  ((mwm > 1024)) && mwm=1024
  export PG_TUNE_RAM_MB=$ram_mb PG_TUNE_CPUS=$cpus
  export PG_TUNE_MAX_WORKERS=$((cpus > 8 ? cpus : 8))
  export PG_TUNE_PARALLEL_PER_GATHER=$((cpus / 2 > 4 ? 4 : (cpus / 2 < 1 ? 1 : cpus / 2)))
  [[ $PG_SHARED_BUFFERS == auto ]] && PG_TUNE_SHARED_BUFFERS="${sb}MB" || PG_TUNE_SHARED_BUFFERS=$PG_SHARED_BUFFERS
  [[ $PG_EFFECTIVE_CACHE_SIZE == auto ]] && PG_TUNE_EFFECTIVE_CACHE_SIZE="${ecs}MB" || PG_TUNE_EFFECTIVE_CACHE_SIZE=$PG_EFFECTIVE_CACHE_SIZE
  [[ $PG_WORK_MEM == auto ]] && PG_TUNE_WORK_MEM="${wm}MB" || PG_TUNE_WORK_MEM=$PG_WORK_MEM
  [[ $PG_MAINTENANCE_WORK_MEM == auto ]] && PG_TUNE_MAINTENANCE_WORK_MEM="${mwm}MB" || PG_TUNE_MAINTENANCE_WORK_MEM=$PG_MAINTENANCE_WORK_MEM
  export PG_TUNE_SHARED_BUFFERS PG_TUNE_EFFECTIVE_CACHE_SIZE PG_TUNE_WORK_MEM PG_TUNE_MAINTENANCE_WORK_MEM
  if is_true "$BACKUP_PITR"; then export PG_ARCHIVE_MODE=on; else export PG_ARCHIVE_MODE=off; fi
}

